"""`make eval` and friends (spec §10.6, §10.7).

    python -m eval.harness.run eval [--fast]      full evaluation -> eval/results/eval.json
    python -m eval.harness.run verify             regenerate and diff against the committed results
    python -m eval.harness.run report             eval.json -> eval/results/REPORT.md
    python -m eval.harness.run check-leakage      subject-disjointness gate
    python -m eval.harness.run compare A B        refuses mismatched manifests without an override

Every number in the committed results must be regenerated by `verify` on a clean checkout
(§0.1). Anything that varies between machines — timestamps, library builds — is kept out
of the compared payload.
"""
from __future__ import annotations

import argparse
import json
import math
import platform
import sys
from collections import Counter
from pathlib import Path

import numpy as np

from core.pipeline import PipelineConfig, analysis_stages, analyze_pose, analyze_video
from core.registry import default_registry
from core.staging import ArtifactStore, StageSpec, manifest
from eval.harness import corpus
from eval.harness.splits import check_leakage, manifest_rows
from eval.harness.synthetic import GENERATOR_VERSION, generate
from eval.metrics import segmentation as l2

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "eval" / "results"
CLIPS = ROOT / "data" / "clips"
MANIFESTS = ROOT / "data" / "manifests"
ARTIFACTS = ROOT / "artifacts"
RESULTS_SCHEMA = 1
BOOTSTRAP_SEED = 7
FLOAT_TOLERANCE = 1e-6
VOLATILE_KEYS = ("environment",)

NOT_BUILT = {
    "L0": ("not_implemented", "M5 station classifier, M8 real submissions"),
    "L1": ("not_implemented", "needs hand-annotated keypoints (M1 study)"),
    "L3": ("not_implemented", "M4 — needs rater-consensus labels"),
    "L4": ("not_implemented", "M6 — needs calibration split"),
    "L5": ("not_implemented", "M7 — coaching layer"),
}


def _clean(obj):
    """Strict JSON: numpy -> Python, NaN/inf -> None."""
    if isinstance(obj, dict):
        return {str(k): _clean(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_clean(v) for v in obj]
    if isinstance(obj, np.generic):
        obj = obj.item()
    if isinstance(obj, float) and not math.isfinite(obj):
        return None
    return obj


def _environment() -> dict:
    import cv2
    import pydantic
    import scipy
    import yaml
    return {"python": platform.python_version(), "platform": platform.platform(),
            "numpy": np.__version__, "scipy": scipy.__version__, "opencv": cv2.__version__,
            "pydantic": pydantic.__version__, "pyyaml": yaml.__version__}


def _pred_reps(report: dict) -> list[dict]:
    seg = report["diagnostics"].get("segmentation")
    return seg["reps"] if seg else []


def run_synthetic(items, cfg: PipelineConfig, registry, resamples: int) -> tuple[dict, list[dict]]:
    rows, per_item = [], []
    for it in items:
        clip = generate(it.params)
        report = analyze_pose(clip.pose, it.exercise_id, station_requested="S-LAT",
                              station_verified=False, registry=registry, cfg=cfg)
        m = l2.item_metrics(_pred_reps(report), corpus.synthetic_truth_reps(clip), clip.truth.fps)
        row = {"item_id": it.item_id, "subject_id": it.subject_id, "gym_id": it.gym_id,
               "exercise_id": it.exercise_id, "split": it.split, "status": report["status"],
               "abstention": (report["submission_abstention"] or {}).get("reason"), **m}
        rows.append(row)
        per_item.append({"row": row, "params": {k: getattr(it.params, k) for k in (
            "n_reps", "partial_first", "bystander", "noise_px", "miss_rate", "rom_decay_per_rep",
            "turn_pause_s", "start_pause_s", "swing_deg")}})
    agg = l2.aggregate(rows, n_resamples=resamples, seed=BOOTSTRAP_SEED)
    agg["abstained_clips"] = sum(1 for r in rows if r["status"] == "abstained")
    return agg, per_item


def run_real(items, cfg: PipelineConfig, registry, resamples: int) -> tuple[dict | None, list[dict]]:
    if not items:
        return None, []
    try:
        from core.pose.rtmpose import RTMPoseBackend
        backend = RTMPoseBackend()
    except Exception as e:
        return {"clips": 0, "skipped_all": f"pose backend unavailable: {e}"}, []
    store = ArtifactStore(ARTIFACTS)
    rows, errors = [], []
    for it in items:
        try:
            report = analyze_video(it.video_path, it.labels.exercise, station_requested=it.labels.station,
                                   store=store, backend=backend, registry=registry, cfg=cfg)
            from core.pipeline import ingest_cached
            _, ing = ingest_cached(it.video_path, store, cfg)
            truth = corpus.real_truth_reps(it.labels, ing.timestamps_s)
            m = l2.item_metrics(_pred_reps(report), truth, ing.target_fps)
            rows.append({"item_id": it.labels_path.name, "subject_id": it.labels.subject_id,
                         "gym_id": it.labels.gym_id, "exercise_id": it.labels.exercise, "split": it.split,
                         "status": report["status"], **m})
        except Exception as e:
            errors.append({"labels": it.labels_path.name, "reason": type(e).__name__, "detail": str(e)[:300]})
    agg = l2.aggregate(rows, n_resamples=resamples, seed=BOOTSTRAP_SEED) if rows else {"clips": 0}
    agg["errors"] = errors
    return agg, rows


def build_results(fast: bool, include_real: bool = True) -> dict:
    registry = default_registry()
    cfg = PipelineConfig()
    resamples = 1_000 if fast else 10_000
    items = corpus.synthetic_items(n_subjects=12 if fast else 40)

    synth, per_item = run_synthetic(items, cfg, registry, resamples)
    real_list, refused = corpus.real_items(CLIPS) if include_real else ([], [])
    real, _ = run_real(real_list, cfg, registry, resamples)
    real_processed = (real or {}).get("clips", 0)

    stages = [StageSpec("synthetic_generator", GENERATOR_VERSION,
                        {"corpus_seed": corpus.CORPUS_SEED, "subjects": len({i.subject_id for i in items})}),
              *analysis_stages(cfg, registry)]
    man = manifest(stages, {"results_schema": RESULTS_SCHEMA, "bootstrap_seed": BOOTSTRAP_SEED,
                            "resamples": resamples})

    worst = sorted(per_item, key=lambda p: (-p["row"]["abs_count_error"],
                                             -max([*sum(p["row"]["boundary_error_ms"].values(), []), 0])))[:10]
    real_gate = (real or {}).get("l2_gate", {}).get("passes", False)
    results = {
        "schema_version": RESULTS_SCHEMA,
        "mode": "fast" if fast else "full",
        "manifest": man,
        "corpora": {
            "synthetic": {
                "admissible": False,
                "why": "Synthetic clips prove the signal path is correct. They are never evidence "
                       "about real video and cannot satisfy a tier gate or success criterion.",
                "clips": len(items), "subjects": len({i.subject_id for i in items}),
                "exercises": dict(sorted(Counter(i.exercise_id for i in items).items())),
                "splits": dict(sorted(Counter(i.split for i in items).items())),
            },
            "real": {
                "admissible": True, "clips_found": len(real_list) + len(refused),
                "clips_processed": real_processed, "refused": refused,
            },
        },
        "layers": {
            **{k: {"status": s, "milestone": m} for k, (s, m) in NOT_BUILT.items()},
            "L2": {"status": "measured", "synthetic": synth, "real": real},
        },
        "milestones": {
            "M0": {"exit_criterion": "make eval runs end-to-end on 3 hand-placed clips and emits a results JSON",
                   "met": real_processed >= 3,
                   "evidence": f"{real_processed} real clip(s) processed; synthetic clips do not count"},
            "M1": {"exit_criterion": "Rep-count MAE < 0.5 and off-by-one accuracy > 0.90 on 100 hand-annotated clips",
                   "met": bool(real_processed >= 100 and real_gate),
                   "evidence": f"{real_processed} hand-annotated clip(s); gate "
                               f"{'passes' if real_gate else 'not passed'}"},
        },
        "leakage": {"violations": check_leakage([(i.subject_id, i.split) for i in items]
                                                + manifest_rows(MANIFESTS))},
        "error_analysis": {"worst_synthetic_items": worst},
        "environment": _environment(),
    }
    return _clean(results)


def _comparable(results: dict) -> dict:
    return {k: v for k, v in results.items() if k not in VOLATILE_KEYS}


def _diff(a, b, path="") -> list[str]:
    if isinstance(a, dict) and isinstance(b, dict):
        out = []
        for k in sorted(set(a) | set(b)):
            if k not in a or k not in b:
                out.append(f"{path}/{k}: present in only one")
            else:
                out += _diff(a[k], b[k], f"{path}/{k}")
        return out
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            return [f"{path}: length {len(a)} != {len(b)}"]
        return sum((_diff(x, y, f"{path}[{i}]") for i, (x, y) in enumerate(zip(a, b, strict=True))), [])
    if isinstance(a, float) and isinstance(b, float):
        return [] if math.isclose(a, b, rel_tol=FLOAT_TOLERANCE, abs_tol=FLOAT_TOLERANCE) \
            else [f"{path}: {a} != {b}"]
    return [] if a == b else [f"{path}: {a!r} != {b!r}"]


def _fmt_ci(m: dict | None, unit: str = "") -> str:
    if not m or m.get("value") is None:
        return "—"
    lo, hi = m["ci95"]
    return f"{m['value']:.3f}{unit} [{lo:.3f}, {hi:.3f}] (n={m['n']}, subjects={m['clusters']})"


def render_report(results: dict) -> str:
    syn = results["layers"]["L2"]["synthetic"]
    real = results["layers"]["L2"]["real"]
    lines = [
        "# Plumbline evaluation report",
        "",
        f"Generated by `make report` from `eval/results/eval.json` · mode `{results['mode']}` · "
        f"manifest `{results['manifest']['manifest_hash'][:16]}`",
        "",
        "> **Synthetic numbers are not results.** They show the signal path recovers known ground "
        "truth. They say nothing about real video and cannot satisfy a tier gate or success criterion.",
        "",
        "## Milestones",
        "",
        "| Milestone | Exit criterion | Met | Evidence |",
        "|---|---|---|---|",
    ]
    for k, m in results["milestones"].items():
        lines.append(f"| {k} | {m['exit_criterion']} | {'yes' if m['met'] else '**no**'} | {m['evidence']} |")
    lines += ["", "## Layers", "", "| Layer | Status | Milestone |", "|---|---|---|"]
    for k in ("L0", "L1", "L2", "L3", "L4", "L5"):
        layer = results["layers"][k]
        lines.append(f"| {k} | {layer['status']} | {layer.get('milestone', '—')} |")
    lines += ["", "## L2 segmentation — synthetic corpus (not admissible)", "",
              f"{syn['clips']} clips, {syn['subjects']} subjects, {syn.get('abstained_clips', 0)} abstained.", "",
              "| Metric | Value [95% CI] |", "|---|---|",
              f"| Rep-count MAE | {_fmt_ci(syn['rep_count_mae'])} |",
              f"| Off-by-one accuracy | {_fmt_ci(syn['off_by_one_accuracy'])} |",
              f"| Exact-count accuracy | {_fmt_ci(syn['exact_count_accuracy'])} |",
              f"| Phase-label accuracy | {_fmt_ci(syn['phase_label_accuracy'])} |"]
    for b, m in syn["boundary_error_ms"].items():
        lines.append(f"| Boundary error, {b} (ms) | {_fmt_ci(m)} |")
    lines += ["", "| Exercise | Clips | Rep-count MAE | Off-by-one | Gate on this corpus |", "|---|---|---|---|---|"]
    for ex, s in syn["by_exercise"].items():
        lines.append(f"| {ex} | {s['clips']} | {_fmt_ci(s['rep_count_mae'])} | "
                     f"{_fmt_ci(s['off_by_one_accuracy'])} | {'passes' if s['l2_gate']['passes'] else 'fails'} "
                     f"(inadmissible) |")
    lines += ["", "## L2 segmentation — real clips", ""]
    if not real:
        lines.append("No hand-placed clips yet. See `data/clips/README.md`.")
    elif real.get("skipped_all"):
        lines.append(f"Skipped: {real['skipped_all']}")
    else:
        lines += [f"{real['clips']} clips processed.", "",
                  f"- Rep-count MAE: {_fmt_ci(real.get('rep_count_mae'))}",
                  f"- Off-by-one accuracy: {_fmt_ci(real.get('off_by_one_accuracy'))}"]
    refused = results["corpora"]["real"]["refused"]
    if refused:
        lines += ["", "Refused clips:", *[f"- `{r['labels']}`: {r['reason']}" for r in refused]]
    lines += ["", "## Leakage", "",
              "No subject appears in more than one split." if not results["leakage"]["violations"]
              else f"**{len(results['leakage']['violations'])} violations.**", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to cp1252
    ap = argparse.ArgumentParser(prog="eval.harness.run")
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("eval")
    e.add_argument("--fast", action="store_true")
    e.add_argument("--out", type=Path)
    e.add_argument("--no-real", action="store_true")
    v = sub.add_parser("verify")
    v.add_argument("--results", type=Path, default=RESULTS / "eval.json")
    r = sub.add_parser("report")
    r.add_argument("--results", type=Path, default=RESULTS / "eval.json")
    r.add_argument("--out", type=Path, default=RESULTS / "REPORT.md")
    sub.add_parser("check-leakage")
    c = sub.add_parser("compare")
    c.add_argument("a", type=Path)
    c.add_argument("b", type=Path)
    c.add_argument("--allow-manifest-mismatch", action="store_true")
    args = ap.parse_args(argv)

    if args.cmd == "eval":
        results = build_results(args.fast, include_real=not args.no_real)
        out = args.out or RESULTS / ("eval-fast.json" if args.fast else "eval.json")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(results, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        syn = results["layers"]["L2"]["synthetic"]
        print(f"wrote {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}")
        print(f"  synthetic L2: MAE {_fmt_ci(syn['rep_count_mae'])}; off-by-one {_fmt_ci(syn['off_by_one_accuracy'])}")
        for k, m in results["milestones"].items():
            print(f"  {k} exit criterion met: {m['met']} — {m['evidence']}")
        return 0

    if args.cmd == "verify":
        committed = json.loads(args.results.read_text(encoding="utf-8"))
        fresh = build_results(committed["mode"] == "fast")
        if committed["manifest"]["manifest_hash"] != fresh["manifest"]["manifest_hash"]:
            print("FAIL: pipeline manifest changed but committed results were not regenerated.\n"
                  "      Run `make eval` and commit eval/results/ in the same change.")
            return 1
        problems = _diff(_comparable(committed), _comparable(fresh))
        if problems:
            print("FAIL: committed results are not reproducible from this checkout:")
            print("\n".join(f"  {p}" for p in problems[:40]))
            return 1
        print(f"OK: {args.results.name} reproduces exactly (manifest {fresh['manifest']['manifest_hash'][:16]})")
        return 0

    if args.cmd == "report":
        results = json.loads(args.results.read_text(encoding="utf-8"))
        args.out.write_text(render_report(results), encoding="utf-8")
        print(f"wrote {args.out}")
        return 0

    if args.cmd == "check-leakage":
        rows = [(i.subject_id, i.split) for i in corpus.synthetic_items()] + manifest_rows(MANIFESTS)
        violations = check_leakage(rows)
        if violations:
            print(f"FAIL: {len(violations)} subject(s) in more than one split: {violations[:10]}")
            return 1
        print(f"OK: {len({s for s, _ in rows})} subjects, none shared across splits")
        return 0

    if args.cmd == "compare":
        a, b = json.loads(args.a.read_text(encoding="utf-8")), json.loads(args.b.read_text(encoding="utf-8"))
        ha, hb = a["manifest"]["manifest_hash"], b["manifest"]["manifest_hash"]
        if ha != hb and not args.allow_manifest_mismatch:
            print(f"REFUSED: manifests differ ({ha[:12]} vs {hb[:12]}). These numbers come from "
                  "different pipelines. Pass --allow-manifest-mismatch to compare anyway.")
            return 2
        for key in ("rep_count_mae", "off_by_one_accuracy", "exact_count_accuracy", "phase_label_accuracy"):
            va = a["layers"]["L2"]["synthetic"][key]["value"]
            vb = b["layers"]["L2"]["synthetic"][key]["value"]
            print(f"  {key:24s} {va:.4f} -> {vb:.4f} ({vb - va:+.4f})")
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
